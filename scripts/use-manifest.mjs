#!/usr/bin/env node
// Materialises manifest.yml for one distribution.
//
//   node scripts/use-manifest.mjs marketplace
//   node scripts/use-manifest.mjs internal
//
// The Forge CLI only ever reads ./manifest.yml, and there is no --app-id flag
// (checked against CLI 16.0.0), so switching apps means rewriting that file.
// Doing it through a script rather than by hand is the whole safety mechanism:
// deploying the Dash-internal build over the marketplace app, or the reverse,
// is a silent mistake that would only surface as a mass of confused users.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TEMPLATE = path.join(ROOT, 'manifests', 'manifest.template.yml');
const VARIANTS = path.join(ROOT, 'manifests', 'variants.json');
const OUTPUT = path.join(ROOT, 'manifest.yml');

const PLACEHOLDERS = {
  __APP_ID__: 'appId',
  __APP_TITLE__: 'appTitle',
  __APP_ROUTE__: 'appRoute',
  __LICENSING_ENABLED__: 'licensingEnabled',
};

function fail(message) {
  console.error(`\nuse-manifest: ${message}\n`);
  process.exit(1);
}

const name = process.argv[2];
const variants = JSON.parse(fs.readFileSync(VARIANTS, 'utf8'));
const available = Object.keys(variants).filter((key) => !key.startsWith('_'));

if (!name) {
  fail(`which distribution? one of: ${available.join(', ')}`);
}

const variant = variants[name];
if (!variant || name.startsWith('_')) {
  fail(`unknown distribution "${name}". Available: ${available.join(', ')}`);
}

// The guard that matters. An empty app id means `forge register` has not been
// run for this distribution yet; proceeding would write a manifest the CLI
// either rejects or — worse — resolves to the other app.
if (!variant.appId || !variant.appId.startsWith('ari:cloud:ecosystem::app/')) {
  fail(
    `"${name}" has no valid app id yet.\n` +
      `  Register it first (interactive — it accepts Atlassian's developer terms,\n` +
      `  so a person has to run it):\n\n` +
      `      forge register\n\n` +
      `  Then put the generated id into manifests/variants.json under "${name}".\n` +
      `  Nothing has been written; manifest.yml is unchanged.`,
  );
}

let output = fs.readFileSync(TEMPLATE, 'utf8');

for (const [placeholder, field] of Object.entries(PLACEHOLDERS)) {
  const value = variant[field];
  if (value === undefined || value === null || value === '') {
    fail(`variant "${name}" is missing "${field}"`);
  }
  output = output.split(placeholder).join(String(value));
}

const leftover = output.match(/__[A-Z_]+__/g);
if (leftover) {
  fail(`template still contains unsubstituted placeholders: ${[...new Set(leftover)].join(', ')}`);
}

// Stamp which distribution this is, so anyone looking at manifest.yml — or at a
// CI log — can see what they are about to deploy without decoding an ARI.
const stamp = [
  `# DISTRIBUTION: ${variant.label} (${name})`,
  `# Generated by scripts/use-manifest.mjs — regenerate, do not edit.`,
  '',
].join('\n');

fs.writeFileSync(OUTPUT, stamp + output, 'utf8');

console.log(`manifest.yml -> ${variant.label} (${name})`);
console.log(`  app id : ${variant.appId}`);
console.log(`  title  : ${variant.appTitle}`);
console.log(`  licence: ${variant.licensingEnabled ? 'enabled' : 'disabled'}`);
